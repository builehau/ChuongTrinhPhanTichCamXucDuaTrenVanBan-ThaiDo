def main() -> None:
    output = Path(__file__).with_name("sentiment_vi.csv")
    rows = [(text, label) for label, texts in SAMPLES.items() for text in texts]
    if len({text.lower() for text, _ in rows}) != len(rows):
        raise ValueError("Bộ dữ liệu có câu bị trùng.")
    with output.open("w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file)
        writer.writerow(["text", "label"])
        writer.writerows(rows)
    print(f"Đã tạo {len(rows)} mẫu tại {output}")
    for label, texts in SAMPLES.items():
        print(f"- {label}: {len(texts)} mẫu")


if __name__ == "__main__":
    main()
